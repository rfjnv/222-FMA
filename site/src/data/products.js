export const bySlug = (handle) => products.find((p) => p.handle === handle);

export const CATEGORIES = ['men', 'women', 'knit', 'shoes-acc'];

export function inCategory(p, cat) {
  if (!cat || cat === 'all') return true;
  if (cat === 'knit') return p.tags.includes('knit');
  if (cat === 'shoes-acc') return p.cat === 'shoes' || p.cat === 'acc';
  return p.cat === cat;
}
